"""Build the MV/LV service-zone alternative.

Heuristic, not a facility-location optimizer (per MVP scope). The whole grid-connected
customer set is partitioned into **capacity-limited service zones** (bounded by a maximum LV
zone radius and the largest transformer rating). Each zone gets a transformer placed at the
zone centroid (snapped to the nearest road when available) and a local LV tree generated by the
existing topology engine. The MV trunk from the source to the transformers is an MST.

Full-settlement zoning (rather than one big LV "core" plus a few remote clusters) is what makes
large, dense villages feasible: a single 0.4 kV network cannot serve hundreds of customers over
hundreds of metres without voltage collapse.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Tuple

import geopandas as gpd
import networkx as nx
import numpy as np
import pandas as pd
from scipy.cluster.hierarchy import fcluster, linkage
from scipy.cluster.vq import kmeans2
from scipy.spatial import ConvexHull, QhullError
from scipy.spatial.distance import pdist
from shapely.geometry import Point
from shapely.ops import nearest_points

from .lv_topology import LVTopology, build_lv_topology

_HULL_MIN_POINTS = 500  # above this cluster size, reduce to convex-hull vertices before pdist


@dataclass
class MVLVPlan:
    core_topology: Optional[LVTopology]  # kept for builder compatibility; always None here
    zones: List[Dict[str, Any]] = field(default_factory=list)
    mv_total_length_m: float = 0.0
    core_customer_ids: List[str] = field(default_factory=list)
    zone_customer_ids: List[str] = field(default_factory=list)
    mv_topology: Optional[LVTopology] = None
    clustering_criterion: str = ""
    mv_iterations: List[Dict[str, Any]] = field(default_factory=list)
    # Why this zone count was chosen (margin held / margin unreachable / nothing feasible).
    selection_note: str = ""


def _customer_kva(customers_df: pd.DataFrame, horizon_years: int) -> Dict[str, float]:
    by = customers_df.set_index("customer_id")
    p = by["peak_kw_now"] * (1.0 + by["growth_rate"]) ** horizon_years
    q = p * (((1.0 / by["power_factor"].clip(0.5, 1.0)) ** 2 - 1.0) ** 0.5)
    s = (p * p + q * q) ** 0.5
    return {str(k): float(v) for k, v in s.items()}


def zone_apparent_power_kva(
    customer_ids: List[str],
    customers_df: pd.DataFrame,
    horizon_years: int,
    coincidence_factor: float = 1.0,
) -> float:
    """Horizon apparent power of a customer group [kVA], diversified by ``coincidence_factor``.

    Apparent power is the vector sum of P and Q, not the sum of |S|.

    ``coincidence_factor`` must be the SAME diversity assumption the network is validated
    against. Sizing at 1.0 while the design power flow runs at ``cf`` makes the transformer
    ``1/cf`` times larger than the snapshot it is checked against (2.0x at the 0.6 default,
    on top of the 1.2 sizing margin), so transformer loading could never approach its limit
    and the constraint never bound. See ``transformer_sizing_coincidence_factor``.
    """
    by = customers_df.set_index("customer_id")
    rows = by.loc[[c for c in customer_ids if c in by.index]]
    cf = float(coincidence_factor)
    p = (rows["peak_kw_now"] * (1.0 + rows["growth_rate"]) ** horizon_years) * cf
    q = p * (((1.0 / rows["power_factor"].clip(0.5, 1.0)) ** 2 - 1.0) ** 0.5)
    return math.sqrt(float(p.sum()) ** 2 + float(q.sum()) ** 2)


def select_transformer(s_zone_kva: float, transformers_df: pd.DataFrame, *, safety_factor: float = 1.2) -> Dict[str, Any]:
    """Smallest transformer (lowest rank) covering the zone with a sizing safety margin.

    The margin accounts for losses/reactive flow (which raise the real loading a few percent
    above the nominal apparent power) and gives realistic distribution-transformer headroom.
    """
    target = float(s_zone_kva) * float(safety_factor)
    ok = transformers_df[transformers_df["sn_kva"] * transformers_df["max_loading_percent"] / 100.0 >= target]
    chosen = (ok.sort_values("rank").iloc[0] if not ok.empty else transformers_df.sort_values("rank").iloc[-1])
    return chosen.to_dict()


def partition_service_zones(
    customer_ids: List[str],
    customers_engine_gdf: gpd.GeoDataFrame,
    source: Dict[str, Any],
    crs_epsg: int,
    *,
    customers_df: pd.DataFrame,
    horizon_years: int,
    max_zone_radius_m: float,
    max_zone_kva: float,
    max_zone_customers: int = 80,
) -> List[List[str]]:
    """Greedy farthest-first partition into compact, capacity-limited zones (deterministic)."""
    wanted = set(map(str, customer_ids))
    sub = customers_engine_gdf[customers_engine_gdf["customer_id"].astype(str).isin(wanted)]
    xy = {str(cid): (float(g.x), float(g.y)) for cid, g in zip(sub["customer_id"], sub.geometry)}
    src = gpd.GeoSeries.from_xy([source["longitude"]], [source["latitude"]], crs="EPSG:4326").to_crs(epsg=crs_epsg).iloc[0]
    src_xy = (float(src.x), float(src.y))
    kva = _customer_kva(customers_df, horizon_years)

    unassigned = set(xy)
    zones: List[List[str]] = []
    while unassigned:
        seed = max(unassigned, key=lambda c: (math.dist(xy[c], src_xy), c))
        members = [seed]
        unassigned.discard(seed)
        zkva = kva.get(seed, 0.0)
        for c in sorted(unassigned, key=lambda c: (math.dist(xy[c], xy[seed]), c)):
            if math.dist(xy[c], xy[seed]) > max_zone_radius_m:
                break  # sorted by distance -> all remaining are farther
            if len(members) >= max_zone_customers or zkva + kva.get(c, 0.0) > max_zone_kva:
                continue
            members.append(c)
            unassigned.discard(c)
            zkva += kva.get(c, 0.0)
        zones.append(sorted(members))
    return zones


# =============================================================================
# Criterion-driven partitioning (distance cap / voltage cap)
#
# Pure geometry: these never decide how many transformers to build. The k-search
# for the voltage cap lives in the workflow runner (``mvp_runner._build_mvlv``),
# mirroring the reference split between partitioning and the reinforcement loop.
# All three criteria funnel through ``enforce_kva_cap`` so the transformer kVA
# cap (largest procurable rating) is preserved regardless of how clusters form.
# =============================================================================
def _coords_and_ids(customer_ids: List[str], customers_engine_gdf: gpd.GeoDataFrame) -> Tuple[np.ndarray, List[str]]:
    """(N, 2) projected-metre coordinates and the aligned customer-id list."""
    wanted = set(map(str, customer_ids))
    sub = customers_engine_gdf[customers_engine_gdf["customer_id"].astype(str).isin(wanted)]
    ids = [str(c) for c in sub["customer_id"]]
    coords = np.column_stack([sub.geometry.x.to_numpy(dtype=float), sub.geometry.y.to_numpy(dtype=float)])
    return coords, ids


def _labels_to_groups(ids: List[str], labels: np.ndarray) -> List[List[str]]:
    """Group ids by integer cluster label, returned in stable label order."""
    buckets: Dict[int, List[str]] = {}
    for cid, lab in zip(ids, labels):
        buckets.setdefault(int(lab), []).append(cid)
    return [sorted(v) for _, v in sorted(buckets.items())]


def cluster_diameters_m(coords_m: np.ndarray, labels: np.ndarray) -> Dict[int, float]:
    """Diameter (max intra-cluster pairwise distance, metres) of each cluster.

    Large clusters are first reduced to their convex-hull vertices (the diameter
    of a planar point set is attained by hull points), with a plain ``pdist``
    fallback for collinear/degenerate geometries.
    """
    coords = np.asarray(coords_m, dtype=float)
    labels = np.asarray(labels, dtype=int)
    out: Dict[int, float] = {}
    for lab in np.unique(labels):
        pts = coords[labels == lab]
        if pts.shape[0] < 2:
            out[int(lab)] = 0.0
            continue
        if pts.shape[0] >= _HULL_MIN_POINTS:
            try:
                pts = pts[ConvexHull(pts).vertices]
            except QhullError:
                pass
        out[int(lab)] = float(pdist(pts).max())
    return out


def partition_complete_linkage(coords_m: np.ndarray, max_diameter_m: float) -> np.ndarray:
    """Complete-linkage hierarchical clustering cut at ``max_diameter_m``.

    Complete linkage merges, at each step, the pair whose merge yields the
    smallest possible diameter; cutting the dendrogram at the threshold returns
    clusters whose diameter is <= the cap BY CONSTRUCTION, with the number of
    clusters emerging from the cut (no k to guess, deterministic, no PF).
    """
    coords = np.asarray(coords_m, dtype=float)
    n = coords.shape[0]
    if max_diameter_m <= 0:
        raise ValueError(f"max_diameter_m must be > 0; got {max_diameter_m}")
    if n <= 1:
        return np.zeros(n, dtype=int)
    Z = linkage(coords, method="complete")
    return (fcluster(Z, t=float(max_diameter_m), criterion="distance") - 1).astype(int)


def partition_kmeans(coords_m: np.ndarray, n_clusters: int, seed: int = 42, retries: int = 5) -> np.ndarray:
    """Spatial k-means into exactly ``n_clusters`` non-empty compact clusters.

    Deterministic given ``seed`` (fixed init, retried on degenerate draws).
    """
    coords = np.asarray(coords_m, dtype=float)
    n = coords.shape[0]
    if n_clusters <= 1:
        return np.zeros(n, dtype=int)
    if n_clusters > n:
        raise ValueError(f"{n_clusters} clusters requested but only {n} customers")
    for attempt in range(retries):
        rng_seed = int(seed) + attempt
        np.random.seed(rng_seed)
        try:
            _, labels = kmeans2(coords, n_clusters, minit="++", seed=rng_seed)
        except Exception:
            continue
        if len(np.unique(labels)) == n_clusters:
            return labels.astype(int)
    raise ValueError(
        f"k-means failed to produce {n_clusters} non-empty clusters after {retries} attempts "
        f"(n={n}); too few distinct customer locations for this many zones."
    )


def partition_hierarchical_k(coords_m: np.ndarray, n_clusters: int) -> np.ndarray:
    """Ward-linkage dendrogram cut at exactly ``n_clusters`` -- a NESTED family over k.

    This is what the voltage-cap k-search iterates over, and the nesting is the whole
    point. k-means re-partitions from scratch at every k, so the zones at k+1 bear no
    relation to those at k: adding a transformer can move customers between unrelated
    clusters and make the worst LV voltage drop *worse*. That was measured on the Mafa
    case (k=4 gave a 0.1028 pu drop against k=3's 0.1004 pu), which breaks the
    monotonicity the "backtrack to the minimum feasible k" search assumes.

    Cutting one Ward dendrogram instead means the k+1 partition strictly refines the k
    partition: a zone is split, never reshuffled, so each added transformer can only
    shorten the LV paths inside the zone it splits. Feasibility is then well behaved in k
    (still not formally guaranteed -- transformer placement and the per-zone MST are
    recomputed -- but no longer actively fighting the search).

    Deterministic: no seed, no restarts.
    """
    coords = np.asarray(coords_m, dtype=float)
    n = coords.shape[0]
    if n_clusters <= 1 or n <= 1:
        return np.zeros(n, dtype=int)
    if n_clusters > n:
        raise ValueError(f"{n_clusters} clusters requested but only {n} customers")
    Z = linkage(coords, method="ward")
    labels = fcluster(Z, t=int(n_clusters), criterion="maxclust") - 1
    return labels.astype(int)


def suggest_zone_start(coords_m: np.ndarray, hopeless_diameter_m: float = 2000.0) -> int:
    """Physically-motivated starting number of zones for the voltage-cap loop.

    A cluster wider than ~2 km cannot hold a 10% LV drop at village loads, so
    the complete-linkage cluster count at that "hopeless" diameter is the
    smallest zone count not doomed by geometry. The loop still backtracks below
    this seed, so it never prevents finding the true minimum.
    """
    coords = np.asarray(coords_m, dtype=float)
    if coords.shape[0] <= 1:
        return 1
    Z = linkage(coords, method="complete")
    ncl = len(np.unique(fcluster(Z, t=float(hopeless_diameter_m), criterion="distance")))
    return max(1, int(ncl))


def _split_over_cap(
    group: List[str],
    customers_engine_gdf: gpd.GeoDataFrame,
    customers_df: pd.DataFrame,
    horizon_years: int,
    max_zone_kva: float,
    seed: int,
    coincidence_factor: float = 1.0,
) -> List[List[str]]:
    """Recursively bisect a group until every child is within the kVA cap.

    A single customer whose own apparent power exceeds the cap is returned as a
    singleton (unavoidable: no procurable transformer covers it) — the caller's
    post-condition allows singletons over cap.
    """
    if len(group) <= 1 or zone_apparent_power_kva(
        group, customers_df, horizon_years, coincidence_factor
    ) <= max_zone_kva:
        return [sorted(group)]
    coords, ids = _coords_and_ids(group, customers_engine_gdf)
    try:
        labels = partition_kmeans(coords, 2, seed=seed)
    except ValueError:
        return [[i] for i in ids]  # coincident points: cannot bisect further
    children = _labels_to_groups(ids, labels)
    if len(children) < 2:
        return [[i] for i in ids]
    out: List[List[str]] = []
    for child in children:
        out.extend(_split_over_cap(
            child, customers_engine_gdf, customers_df, horizon_years, max_zone_kva, seed,
            coincidence_factor,
        ))
    return out


def enforce_kva_cap(
    groups: List[List[str]],
    customers_engine_gdf: gpd.GeoDataFrame,
    customers_df: pd.DataFrame,
    horizon_years: int,
    max_zone_kva: float,
    seed: int = 42,
    coincidence_factor: float = 1.0,
) -> List[List[str]]:
    """Split any zone exceeding the largest procurable transformer rating.

    This is what keeps the kVA cap alive under the geometric/electrical criteria:
    complete-linkage and k-means bound *distance*, not load, so a dense compact
    cluster can still exceed the biggest catalogue transformer and must be split.
    """
    out: List[List[str]] = []
    for g in groups:
        if not g:
            continue
        out.extend(_split_over_cap(
            g, customers_engine_gdf, customers_df, horizon_years, max_zone_kva, seed,
            coincidence_factor,
        ))
    return out


def partition_zones(
    criterion: str,
    customer_ids: List[str],
    customers_engine_gdf: gpd.GeoDataFrame,
    source: Dict[str, Any],
    crs_epsg: int,
    *,
    customers_df: pd.DataFrame,
    horizon_years: int,
    max_zone_kva: float,
    max_zone_radius_m: float,
    max_zone_customers: int,
    max_cluster_diameter_m: float = 500.0,
    n_zones: Optional[int] = None,
    seed: int = 42,
    coincidence_factor: float = 1.0,
) -> List[List[str]]:
    """Dispatch to the requested partitioning criterion; all enforce the kVA cap.

    - ``capacity``: greedy farthest-first packing (legacy), already kVA-capped internally.
    - ``distance_cap``: complete-linkage cut at ``max_cluster_diameter_m`` then kVA split.
      Deterministic, one-shot, no power flow.
    - ``voltage_cap``: Ward dendrogram cut at ``n_zones`` then kVA split; the workflow
      runner iterates ``n_zones`` and validates each with a power flow. The cut is nested
      over k (see :func:`partition_hierarchical_k`) so the search is not fighting a
      partition that reshuffles itself at every step.

    ``coincidence_factor`` is the diversity basis for the kVA cap and must match the one
    the network is validated against.
    """
    if criterion == "capacity":
        return partition_service_zones(
            customer_ids, customers_engine_gdf, source, crs_epsg,
            customers_df=customers_df, horizon_years=horizon_years,
            max_zone_radius_m=max_zone_radius_m, max_zone_kva=max_zone_kva,
            max_zone_customers=max_zone_customers,
        )

    coords, ids = _coords_and_ids(customer_ids, customers_engine_gdf)
    if criterion == "distance_cap":
        labels = partition_complete_linkage(coords, float(max_cluster_diameter_m))
        groups = _labels_to_groups(ids, labels)
    elif criterion == "voltage_cap":
        if n_zones is None:
            raise ValueError("voltage_cap partitioning requires n_zones")
        if int(n_zones) <= 1 or coords.shape[0] <= 1:
            groups = [sorted(ids)]
        else:
            labels = partition_hierarchical_k(coords, int(n_zones))
            groups = _labels_to_groups(ids, labels)
    else:
        raise ValueError(f"Unknown clustering_criterion: {criterion!r}")

    return enforce_kva_cap(
        groups, customers_engine_gdf, customers_df, horizon_years, max_zone_kva,
        seed=seed, coincidence_factor=coincidence_factor,
    )


def size_stepup_kva(s_system_kva: float, sizing_margin: float, transformers_df: pd.DataFrame) -> float:
    """Plant step-up rating: system apparent power * margin, snapped to the next
    catalogue size, or rounded up to the next 50 kVA above the catalogue.

    The step-up is a single project-procured unit, so (unlike the zone step-downs
    that respect the kVA cap) it is allowed to exceed the largest catalogue entry.
    """
    target = float(s_system_kva) * float(sizing_margin)
    sizes = sorted(float(s) for s in transformers_df["sn_kva"])
    if target <= 0.0:
        return sizes[0]
    for s in sizes:
        if s >= target:
            return s
    return float(math.ceil(target / 50.0) * 50.0)


def build_stepup_spec(
    s_system_kva: float,
    transformers_df: pd.DataFrame,
    *,
    mv_kv: float,
    lv_kv: float,
    sizing_margin: float = 1.2,
) -> Dict[str, Any]:
    """Electrical spec for the plant LV->MV step-up transformer.

    Per-unit short-circuit / no-load characteristics are inherited from the
    largest catalogue transformer (size-robust); the rating is sized to the whole
    settlement's coincident apparent power and may exceed the catalogue.
    """
    largest = transformers_df.sort_values("sn_kva").iloc[-1].to_dict()
    sn_kva = size_stepup_kva(s_system_kva, sizing_margin, transformers_df)
    scale = sn_kva / float(largest["sn_kva"]) if float(largest["sn_kva"]) > 0 else 1.0
    return {
        "transformer_id": "stepup",
        "sn_kva": float(sn_kva),
        "vn_hv_kv": float(mv_kv),
        "vn_lv_kv": float(lv_kv),
        "vk_percent": float(largest["vk_percent"]),
        "vkr_percent": float(largest["vkr_percent"]),
        "pfe_kw": float(largest.get("pfe_kw", 0.0)) * scale,
        "i0_percent": float(largest.get("i0_percent", 0.0)),
        "max_loading_percent": float(largest.get("max_loading_percent", 100.0)),
        "cost_fixed": float(largest.get("cost_fixed", 0.0)),
        "cost_per_kva": float(largest.get("cost_per_kva", 0.0)),
    }


def _transformer_point(centroid_xy, crs_epsg: int, roads_gdf: Optional[gpd.GeoDataFrame]):
    pt = Point(*centroid_xy)
    if roads_gdf is not None and not roads_gdf.empty:
        union = roads_gdf.to_crs(epsg=crs_epsg).geometry.union_all()
        if union is not None and not union.is_empty:
            try:
                snapped = nearest_points(pt, union)[1]
                if snapped is not None and not snapped.is_empty:
                    pt = snapped
            except Exception:
                pass
    latlon = gpd.GeoSeries([pt], crs=f"EPSG:{crs_epsg}").to_crs(epsg=4326).iloc[0]
    return pt, (float(latlon.y), float(latlon.x))


def _mv_nodes_gdf(zones: List[Dict[str, Any]], source: Dict[str, Any], crs_epsg: int) -> gpd.GeoDataFrame:
    """Projected pseudo-customers used to route the MV pole tree."""
    rows = [
        {
            "customer_id": "__source__",
            "consumer_type": "source",
            "priority_score": 5,
            "must_connect_flag": True,
            "must_standalone_flag": False,
            "geometry": Point(float(source["longitude"]), float(source["latitude"])),
        }
    ]
    for zone in zones:
        lat, lon = zone["transformer_latlon"]
        rows.append(
            {
                "customer_id": zone["zone_id"],
                "consumer_type": "transformer",
                "priority_score": 5,
                "must_connect_flag": True,
                "must_standalone_flag": False,
                "geometry": Point(float(lon), float(lat)),
            }
        )
    return gpd.GeoDataFrame(rows, geometry="geometry", crs="EPSG:4326").to_crs(epsg=crs_epsg)


def _build_mv_topology(
    zones: List[Dict[str, Any]],
    roads_gdf: Optional[gpd.GeoDataFrame],
    crs_meta: Dict[str, Any],
    source: Dict[str, Any],
    eng: Dict[str, Any],
) -> Optional[LVTopology]:
    if not zones:
        return None
    crs_epsg = int(crs_meta.get("projected_crs_epsg") or 32633)
    mv_nodes = _mv_nodes_gdf(zones, source, crs_epsg)
    mode = "road_attracted" if roads_gdf is not None and not roads_gdf.empty else "euclidean"
    return build_lv_topology(
        mv_nodes,
        roads_gdf,
        crs_meta,
        source,
        eng,
        edge_weight_mode=mode,
    )


def build_mvlv_plan(
    zone_groups: List[List[str]],
    customers_engine_gdf: gpd.GeoDataFrame,
    roads_gdf: Optional[gpd.GeoDataFrame],
    crs_meta: Dict[str, Any],
    source: Dict[str, Any],
    eng: Dict[str, Any],
    customers_df: pd.DataFrame,
    transformers_df: pd.DataFrame,
    *,
    horizon_years: int,
    coincidence_factor: float = 1.0,
) -> MVLVPlan:
    """One transformer service zone per customer group; MV trunk = MST over the transformers.

    ``coincidence_factor`` is the diversity basis for transformer sizing; pass the same
    value the design power flow uses so the chosen rating and the loading it is checked
    against refer to the same demand.
    """
    crs_epsg = int(crs_meta.get("projected_crs_epsg") or 32633)
    by_ll = customers_df.set_index("customer_id")[["latitude", "longitude"]]

    zones: List[Dict[str, Any]] = []
    for i, group in enumerate(g for g in zone_groups if g):
        zid = f"Z{i:02d}"
        sub = customers_engine_gdf[customers_engine_gdf["customer_id"].astype(str).isin(set(group))]
        centroid_xy = (float(sub.geometry.x.mean()), float(sub.geometry.y.mean()))
        # Clip roads to the zone bbox (+ buffer) so the engine only samples poles along nearby
        # roads — a large speedup vs. sampling the whole network for each small zone.
        zroads = roads_gdf
        if roads_gdf is not None and not roads_gdf.empty:
            gb = by_ll.loc[[c for c in group if c in by_ll.index]]
            buf = 0.004  # ~440 m in degrees
            zroads = roads_gdf.cx[gb["longitude"].min() - buf: gb["longitude"].max() + buf,
                                  gb["latitude"].min() - buf: gb["latitude"].max() + buf]
            if zroads.empty:
                zroads = roads_gdf
        tx_pt, tx_latlon = _transformer_point(centroid_xy, crs_epsg, zroads)
        ztopo = build_lv_topology(
            customers_engine_gdf, zroads, crs_meta,
            {"latitude": tx_latlon[0], "longitude": tx_latlon[1]}, eng, customer_ids=group,
        )
        s_kva = zone_apparent_power_kva(group, customers_df, horizon_years, coincidence_factor)
        tx = select_transformer(s_kva, transformers_df)
        zones.append({
            "zone_id": zid, "cluster_id": zid, "transformer_id": f"{zid}_{tx['transformer_id']}",
            "transformer_spec": tx, "transformer_xy": (float(tx_pt.x), float(tx_pt.y)),
            "transformer_latlon": tx_latlon, "customer_ids": group, "topology": ztopo,
            "s_zone_kva": s_kva, "mv_length_m": 0.0,
        })

    mv_topology = _build_mv_topology(zones, roads_gdf, crs_meta, source, eng)
    mv_total = 0.0
    if mv_topology is not None:
        path_len = nx.single_source_dijkstra_path_length(
            mv_topology.graph,
            mv_topology.slack_pole_id,
            weight="length_m",
        )
        mv_total = mv_topology.total_lv_length_m
        for z in zones:
            zid = z["zone_id"]
            pole_id = mv_topology.customer_pole.get(zid)
            service_drop_m = float(mv_topology.service_drop_m.get(zid, 0.0))
            z["mv_pole_id"] = int(pole_id) if pole_id is not None else None
            z["mv_service_drop_m"] = service_drop_m
            z["mv_length_m"] = float(path_len.get(int(pole_id), 0.0) + service_drop_m) if pole_id is not None else 0.0
            mv_total += service_drop_m

    all_ids = sorted({c for z in zones for c in z["customer_ids"]})
    return MVLVPlan(core_topology=None, zones=zones, mv_total_length_m=mv_total,
                    core_customer_ids=[], zone_customer_ids=all_ids, mv_topology=mv_topology)
