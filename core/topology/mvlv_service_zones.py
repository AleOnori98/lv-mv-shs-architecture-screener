"""Build the MV/LV service-zone alternative.

Heuristic, not a facility-location optimizer (per MVP scope). The whole grid-connected
customer set is partitioned into **capacity-limited service zones** (bounded by a maximum LV
zone radius and the largest transformer rating). Each zone gets a transformer placed at the
zone centroid (snapped to the nearest road when available) and a local LV tree generated by the
existing topology engine. The MV trunk from the source to the transformers is an MST.

Full-settlement zoning (rather than one big LV "core" plus a few remote clusters) is what makes
large, dense villages feasible: a single 0.4 kV network cannot serve hundreds of customers over
hundreds of metres without voltage collapse.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

import geopandas as gpd
import networkx as nx
import pandas as pd
from shapely.geometry import Point
from shapely.ops import nearest_points

from .lv_topology import LVTopology, build_lv_topology


@dataclass
class MVLVPlan:
    core_topology: Optional[LVTopology]  # kept for builder compatibility; always None here
    zones: List[Dict[str, Any]] = field(default_factory=list)
    mv_total_length_m: float = 0.0
    core_customer_ids: List[str] = field(default_factory=list)
    zone_customer_ids: List[str] = field(default_factory=list)
    mv_topology: Optional[LVTopology] = None


def _customer_kva(customers_df: pd.DataFrame, horizon_years: int) -> Dict[str, float]:
    by = customers_df.set_index("customer_id")
    p = by["peak_kw_now"] * (1.0 + by["growth_rate"]) ** horizon_years
    q = p * (((1.0 / by["power_factor"].clip(0.5, 1.0)) ** 2 - 1.0) ** 0.5)
    s = (p * p + q * q) ** 0.5
    return {str(k): float(v) for k, v in s.items()}


def zone_apparent_power_kva(customer_ids: List[str], customers_df: pd.DataFrame, horizon_years: int) -> float:
    kva = _customer_kva(customers_df, horizon_years)
    # Coincident apparent power is the vector sum of P and Q, not the sum of |S|; recompute.
    by = customers_df.set_index("customer_id")
    rows = by.loc[[c for c in customer_ids if c in by.index]]
    p = (rows["peak_kw_now"] * (1.0 + rows["growth_rate"]) ** horizon_years)
    q = p * (((1.0 / rows["power_factor"].clip(0.5, 1.0)) ** 2 - 1.0) ** 0.5)
    return math.sqrt(float(p.sum()) ** 2 + float(q.sum()) ** 2)


def select_transformer(s_zone_kva: float, transformers_df: pd.DataFrame, *, safety_factor: float = 1.2) -> Dict[str, Any]:
    """Smallest transformer (lowest rank) covering the zone with a sizing safety margin.

    The margin accounts for losses/reactive flow (which raise the real loading a few percent
    above the nominal apparent power) and gives realistic distribution-transformer headroom.
    """
    target = float(s_zone_kva) * float(safety_factor)
    ok = transformers_df[transformers_df["sn_kva"] * transformers_df["max_loading_percent"] / 100.0 >= target]
    chosen = (ok.sort_values("rank").iloc[0] if not ok.empty else transformers_df.sort_values("rank").iloc[-1])
    return chosen.to_dict()


def partition_service_zones(
    customer_ids: List[str],
    customers_engine_gdf: gpd.GeoDataFrame,
    source: Dict[str, Any],
    crs_epsg: int,
    *,
    customers_df: pd.DataFrame,
    horizon_years: int,
    max_zone_radius_m: float,
    max_zone_kva: float,
    max_zone_customers: int = 80,
) -> List[List[str]]:
    """Greedy farthest-first partition into compact, capacity-limited zones (deterministic)."""
    wanted = set(map(str, customer_ids))
    sub = customers_engine_gdf[customers_engine_gdf["customer_id"].astype(str).isin(wanted)]
    xy = {str(cid): (float(g.x), float(g.y)) for cid, g in zip(sub["customer_id"], sub.geometry)}
    src = gpd.GeoSeries.from_xy([source["longitude"]], [source["latitude"]], crs="EPSG:4326").to_crs(epsg=crs_epsg).iloc[0]
    src_xy = (float(src.x), float(src.y))
    kva = _customer_kva(customers_df, horizon_years)

    unassigned = set(xy)
    zones: List[List[str]] = []
    while unassigned:
        seed = max(unassigned, key=lambda c: (math.dist(xy[c], src_xy), c))
        members = [seed]
        unassigned.discard(seed)
        zkva = kva.get(seed, 0.0)
        for c in sorted(unassigned, key=lambda c: (math.dist(xy[c], xy[seed]), c)):
            if math.dist(xy[c], xy[seed]) > max_zone_radius_m:
                break  # sorted by distance -> all remaining are farther
            if len(members) >= max_zone_customers or zkva + kva.get(c, 0.0) > max_zone_kva:
                continue
            members.append(c)
            unassigned.discard(c)
            zkva += kva.get(c, 0.0)
        zones.append(sorted(members))
    return zones


def _transformer_point(centroid_xy, crs_epsg: int, roads_gdf: Optional[gpd.GeoDataFrame]):
    pt = Point(*centroid_xy)
    if roads_gdf is not None and not roads_gdf.empty:
        union = roads_gdf.to_crs(epsg=crs_epsg).geometry.union_all()
        if union is not None and not union.is_empty:
            try:
                snapped = nearest_points(pt, union)[1]
                if snapped is not None and not snapped.is_empty:
                    pt = snapped
            except Exception:
                pass
    latlon = gpd.GeoSeries([pt], crs=f"EPSG:{crs_epsg}").to_crs(epsg=4326).iloc[0]
    return pt, (float(latlon.y), float(latlon.x))


def _mv_nodes_gdf(zones: List[Dict[str, Any]], source: Dict[str, Any], crs_epsg: int) -> gpd.GeoDataFrame:
    """Projected pseudo-customers used to route the MV pole tree."""
    rows = [
        {
            "customer_id": "__source__",
            "consumer_type": "source",
            "priority_score": 5,
            "must_connect_flag": True,
            "must_standalone_flag": False,
            "geometry": Point(float(source["longitude"]), float(source["latitude"])),
        }
    ]
    for zone in zones:
        lat, lon = zone["transformer_latlon"]
        rows.append(
            {
                "customer_id": zone["zone_id"],
                "consumer_type": "transformer",
                "priority_score": 5,
                "must_connect_flag": True,
                "must_standalone_flag": False,
                "geometry": Point(float(lon), float(lat)),
            }
        )
    return gpd.GeoDataFrame(rows, geometry="geometry", crs="EPSG:4326").to_crs(epsg=crs_epsg)


def _build_mv_topology(
    zones: List[Dict[str, Any]],
    roads_gdf: Optional[gpd.GeoDataFrame],
    crs_meta: Dict[str, Any],
    source: Dict[str, Any],
    eng: Dict[str, Any],
) -> Optional[LVTopology]:
    if not zones:
        return None
    crs_epsg = int(crs_meta.get("projected_crs_epsg") or 32633)
    mv_nodes = _mv_nodes_gdf(zones, source, crs_epsg)
    mode = "road_attracted" if roads_gdf is not None and not roads_gdf.empty else "euclidean"
    return build_lv_topology(
        mv_nodes,
        roads_gdf,
        crs_meta,
        source,
        eng,
        edge_weight_mode=mode,
    )


def build_mvlv_plan(
    zone_groups: List[List[str]],
    customers_engine_gdf: gpd.GeoDataFrame,
    roads_gdf: Optional[gpd.GeoDataFrame],
    crs_meta: Dict[str, Any],
    source: Dict[str, Any],
    eng: Dict[str, Any],
    customers_df: pd.DataFrame,
    transformers_df: pd.DataFrame,
    *,
    horizon_years: int,
) -> MVLVPlan:
    """One transformer service zone per customer group; MV trunk = MST over the transformers."""
    crs_epsg = int(crs_meta.get("projected_crs_epsg") or 32633)
    by_ll = customers_df.set_index("customer_id")[["latitude", "longitude"]]

    zones: List[Dict[str, Any]] = []
    for i, group in enumerate(g for g in zone_groups if g):
        zid = f"Z{i:02d}"
        sub = customers_engine_gdf[customers_engine_gdf["customer_id"].astype(str).isin(set(group))]
        centroid_xy = (float(sub.geometry.x.mean()), float(sub.geometry.y.mean()))
        # Clip roads to the zone bbox (+ buffer) so the engine only samples poles along nearby
        # roads — a large speedup vs. sampling the whole network for each small zone.
        zroads = roads_gdf
        if roads_gdf is not None and not roads_gdf.empty:
            gb = by_ll.loc[[c for c in group if c in by_ll.index]]
            buf = 0.004  # ~440 m in degrees
            zroads = roads_gdf.cx[gb["longitude"].min() - buf: gb["longitude"].max() + buf,
                                  gb["latitude"].min() - buf: gb["latitude"].max() + buf]
            if zroads.empty:
                zroads = roads_gdf
        tx_pt, tx_latlon = _transformer_point(centroid_xy, crs_epsg, zroads)
        ztopo = build_lv_topology(
            customers_engine_gdf, zroads, crs_meta,
            {"latitude": tx_latlon[0], "longitude": tx_latlon[1]}, eng, customer_ids=group,
        )
        s_kva = zone_apparent_power_kva(group, customers_df, horizon_years)
        tx = select_transformer(s_kva, transformers_df)
        zones.append({
            "zone_id": zid, "cluster_id": zid, "transformer_id": f"{zid}_{tx['transformer_id']}",
            "transformer_spec": tx, "transformer_xy": (float(tx_pt.x), float(tx_pt.y)),
            "transformer_latlon": tx_latlon, "customer_ids": group, "topology": ztopo,
            "s_zone_kva": s_kva, "mv_length_m": 0.0,
        })

    mv_topology = _build_mv_topology(zones, roads_gdf, crs_meta, source, eng)
    mv_total = 0.0
    if mv_topology is not None:
        path_len = nx.single_source_dijkstra_path_length(
            mv_topology.graph,
            mv_topology.slack_pole_id,
            weight="length_m",
        )
        mv_total = mv_topology.total_lv_length_m
        for z in zones:
            zid = z["zone_id"]
            pole_id = mv_topology.customer_pole.get(zid)
            service_drop_m = float(mv_topology.service_drop_m.get(zid, 0.0))
            z["mv_pole_id"] = int(pole_id) if pole_id is not None else None
            z["mv_service_drop_m"] = service_drop_m
            z["mv_length_m"] = float(path_len.get(int(pole_id), 0.0) + service_drop_m) if pole_id is not None else 0.0
            mv_total += service_drop_m

    all_ids = sorted({c for z in zones for c in z["customer_ids"]})
    return MVLVPlan(core_topology=None, zones=zones, mv_total_length_m=mv_total,
                    core_customer_ids=[], zone_customer_ids=all_ids, mv_topology=mv_topology)
